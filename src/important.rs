/// Recognized "important" files that should always be surfaced, even in a
/// crowded directory. These are the files that tell you what a project is.
pub fn is_important(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    const EXACT: &[&str] = &[
        "readme",
        "readme.md",
        "readme.txt",
        "readme.rst",
        "readme.adoc",
        "license",
        "license.md",
        "license.txt",
        "licence",
        "licence.md",
        "copying",
        "unlicense",
        "changelog",
        "changelog.md",
        "changes",
        "changes.md",
        "authors",
        "contributing",
        "contributing.md",
        "code_of_conduct.md",
        "security.md",
        "makefile",
        "makefile.am",
        "justfile",
        "cargo.toml",
        "cargo.lock",
        "rust-toolchain",
        "rust-toolchain.toml",
        "package.json",
        "package-lock.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "go.mod",
        "go.sum",
        "pyproject.toml",
        "setup.py",
        "setup.cfg",
        "requirements.txt",
        "pom.xml",
        "build.gradle",
        "build.gradle.kts",
        "settings.gradle",
        "dockerfile",
        "docker-compose.yml",
        "docker-compose.yaml",
        "compose.yml",
        "compose.yaml",
        "gemfile",
        "gemfile.lock",
        "cmakelists.txt",
        "meson.build",
        ".gitignore",
        ".gitattributes",
        ".gitmodules",
        ".editorconfig",
        ".github",
        "deno.json",
        "bun.lockb",
    ];
    EXACT.contains(&lower.as_str())
}
